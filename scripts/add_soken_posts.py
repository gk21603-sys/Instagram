def main():
    with open(DATA, encoding="utf-8") as f:
        posts = json.load(f)

    existing = {p["images"][0] for p in posts if p.get("images")}
    added = 0
    for post in POSTS:
        if post["images"][0] in existing:
            print("既にあるので飛ばす:", post["images"][0])
            continue
        posts.append(post)
        added += 1

    if added:
        with open(DATA, "w", encoding="utf-8") as f:
            json.dump(posts, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"{added}件を追記しました。合計{len(posts)}件。")
    else:
        print("追記するものはありませんでした。")


if __name__ == "__main__":
    main()
